#!/usr/bin/env python3
"""Generates src/font_data.h: 8-bit alpha glyphs for Latin-1 (32..255) in 3 sizes.

The output is generated at build time from the system Noto Sans (SIL OFL), rendered with PIL,
and is not stored in the repo. Usage: python3 tools/gen_font.py
"""
from PIL import Image, ImageDraw, ImageFont
import os

FONTS = [  # (name in C, file, size in px)
    ('font_small', '/usr/share/fonts/truetype/noto/NotoSans-Regular.ttf', 15),
    ('font_big', '/usr/share/fonts/truetype/noto/NotoSans-Bold.ttf', 26),
    ('font_tiny', '/usr/share/fonts/truetype/noto/NotoSans-Regular.ttf', 12),
]
out = []
out.append('/* Generated by tools/gen_font.py at build time. Do not edit. Noto Sans (SIL OFL). */')
out.append('#pragma once\n#include <stdint.h>')
out.append('typedef struct { int16_t x, y, w, h, adv; uint32_t off; } glyph_t;')
out.append('typedef struct { int size, ascent, line; const glyph_t *g; const uint8_t *a; } font_t;')
for name, path, px in FONTS:
    f = ImageFont.truetype(path, px)
    asc, desc = f.getmetrics()
    glyphs, alpha = [], bytearray()
    for c in range(32, 256):
        ch = chr(c)
        if 127 <= c < 160:
            glyphs.append((0, 0, 0, 0, 0, 0)); continue
        bb = f.getbbox(ch)
        adv = round(f.getlength(ch))
        w, h = max(bb[2] - bb[0], 0), max(bb[3] - bb[1], 0)
        off = len(alpha)
        if w and h:
            im = Image.new('L', (w, h), 0)
            ImageDraw.Draw(im).text((-bb[0], -bb[1]), ch, font=f, fill=255)
            alpha += im.tobytes()
        glyphs.append((bb[0], bb[1], w, h, adv, off))
    out.append(f'static const uint8_t {name}_a[{len(alpha)}] = {{')
    for i in range(0, len(alpha), 24):
        out.append(','.join(str(b) for b in alpha[i:i + 24]) + ',')
    out.append('};')
    out.append(f'static const glyph_t {name}_g[224] = {{')
    out.append(',\n'.join('{%d,%d,%d,%d,%d,%d}' % g for g in glyphs))
    out.append('};')
    out.append(f'static const font_t {name} = {{{px}, {asc}, {asc + desc}, {name}_g, {name}_a}};')
d = os.path.join(os.path.dirname(__file__), '..', 'src', 'font_data.h')
open(d, 'w').write('\n'.join(out) + '\n')
print('ok', d)
