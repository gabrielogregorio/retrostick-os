#!/usr/bin/env python3
"""Generates src/font_data.h: 8-bit alpha glyphs for Latin-1 (32..255) in 3 sizes.

The output is generated at build time from the system Noto Sans (SIL OFL), rendered with PIL,
and is not stored in the repo. Usage: python3 tools/gen_font.py
"""
import os

from PIL import Image, ImageDraw, ImageFont

Glyph = tuple[int, int, int, int, int, int]

REGULAR_FONT = '/usr/share/fonts/truetype/noto/NotoSans-Regular.ttf'
BOLD_FONT = '/usr/share/fonts/truetype/noto/NotoSans-Bold.ttf'
FONTS = [  # (name in C, file, size in px)
    ('font_small', REGULAR_FONT, 15),
    ('font_big', BOLD_FONT, 26),
    ('font_tiny', REGULAR_FONT, 12),
]
FIRST_CHAR = 32
CHAR_LIMIT = 256
CONTROL_RANGE = range(127, 160)  # Latin-1 controls: empty glyphs
GLYPH_COUNT = CHAR_LIMIT - FIRST_CHAR
ALPHA_BYTES_PER_LINE = 24
EMPTY_GLYPH = (0, 0, 0, 0, 0, 0)
HEADER_PREAMBLE = [
    '/* Generated by tools/gen_font.py at build time. Do not edit. Noto Sans (SIL OFL). */',
    '#pragma once\n#include <stdint.h>',
    'typedef struct { int16_t x, y, w, h, adv; uint32_t off; } glyph_t;',
    'typedef struct { int size, ascent, line; const glyph_t *g; const uint8_t *a; } font_t;',
]


def render_glyph(font: ImageFont.FreeTypeFont, char: str, alpha: bytearray) -> Glyph:
    box = font.getbbox(char)
    advance = round(font.getlength(char))
    width = max(box[2] - box[0], 0)
    height = max(box[3] - box[1], 0)
    offset = len(alpha)
    if width and height:
        image = Image.new('L', (width, height), 0)
        ImageDraw.Draw(image).text((-box[0], -box[1]), char, font=font, fill=255)
        alpha += image.tobytes()

    return box[0], box[1], width, height, advance, offset


def render_font(name: str, path: str, size: int) -> list[str]:
    font = ImageFont.truetype(path, size)
    ascent, descent = font.getmetrics()
    glyphs: list[Glyph] = []
    alpha = bytearray()
    for code in range(FIRST_CHAR, CHAR_LIMIT):
        if code in CONTROL_RANGE:
            glyphs.append(EMPTY_GLYPH)
            continue
        glyphs.append(render_glyph(font, chr(code), alpha))
    lines = [f'static const uint8_t {name}_a[{len(alpha)}] = {{']
    for start in range(0, len(alpha), ALPHA_BYTES_PER_LINE):
        lines.append(','.join(str(value) for value in alpha[start:start + ALPHA_BYTES_PER_LINE]) + ',')
    lines.append('};')
    lines.append(f'static const glyph_t {name}_g[{GLYPH_COUNT}] = {{')
    lines.append(',\n'.join('{' + ','.join(map(str, glyph)) + '}' for glyph in glyphs))
    lines.append('};')
    lines.append(f'static const font_t {name} = {{{size}, {ascent}, {ascent + descent}, {name}_g, {name}_a}};')

    return lines


def render_header() -> str:
    lines = list(HEADER_PREAMBLE)
    for name, path, size in FONTS:
        lines += render_font(name, path, size)

    return '\n'.join(lines) + '\n'


def main() -> None:
    destination = os.path.join(os.path.dirname(__file__), '..', 'src', 'font_data.h')
    with open(destination, 'w') as file:
        file.write(render_header())
    print('ok', destination)


if __name__ == '__main__':
    main()
